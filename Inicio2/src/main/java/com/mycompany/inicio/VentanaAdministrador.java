    // {rol en la base de datos, texto del menu}
    private static final String[][] ROLES = {
        {"ADMIN",    "Administradores"},
        {"OFICIAL",  "Oficiales"},
        {"ANALISTA", "Analistas"},
        {"JEFE",     "Jefes de créditos"},
        {"CAJERO",   "Cajeros"},
        {"GESTOR",   "Gestores de cobranza"},
        {"GERENTE",  "Gerentes"}
    };

    private static final String P_INICIO = "INICIO";

    private final String adminLogin;
    private final CardLayout cards = new CardLayout();
    private final Map<String, PanelUsuariosRol> paneles = new HashMap<>();

    public VentanaAdministrador(String adminLogin) {
        Sesion.exigirRol("ADMIN");
        this.adminLogin = adminLogin;
        initComponents();

        // jPanel1 pasa a ser el area de contenido y ocupa toda la ventana
        getContentPane().setLayout(new BorderLayout());
        getContentPane().add(jPanel1, BorderLayout.CENTER);
        jPanel1.setLayout(cards);

        crearPaneles();
        crearMenu();

        setSize(1100, 650);
        setLocationRelativeTo(null);
        cards.show(jPanel1, P_INICIO);
    }

    // Constructor vacio: solo para probar la ventana sola con Run File
    public VentanaAdministrador() {
        this("admin");
    }

    private void crearPaneles() {
        JPanel inicio = new JPanel(new BorderLayout());
        JLabel lbl = new JLabel("<html><div style='text-align:center'>Panel del administrador<br><br>"
                + "<span style='font-size:14px'>Elige un rol en el menu para crear y controlar a sus usuarios.<br>"
                + "Sesion iniciada como: " + adminLogin + "</span></div></html>", SwingConstants.CENTER);
        lbl.setFont(lbl.getFont().deriveFont(Font.BOLD, 26f));
        inicio.add(lbl, BorderLayout.CENTER);
        jPanel1.add(inicio, P_INICIO);

        for (String[] r : ROLES) {
            PanelUsuariosRol p = new PanelUsuariosRol(r[0], adminLogin);
            paneles.put(r[0], p);
            jPanel1.add(p, r[0]);
        }
    }

    private void crearMenu() {
        JMenuItem mniInicio = new JMenuItem("Inicio");
        mniInicio.addActionListener(e -> cards.show(jPanel1, P_INICIO));
        jMenuBar1.add(mniInicio);

        for (String[] r : ROLES) {
            String rol = r[0];
            JMenuItem item = new JMenuItem(r[1]);
            item.addActionListener(e -> {
                paneles.get(rol).cargar();      // siempre muestra datos frescos
                cards.show(jPanel1, rol);
            });
            jMenuBar1.add(item);
        }

        JMenuItem mniSalir = new JMenuItem("Cerrar sesión");
        mniSalir.addActionListener(e -> cerrarSesion());
        jMenuBar1.add(Box.createHorizontalGlue());   // empuja "Cerrar sesion" a la derecha
        jMenuBar1.add(mniSalir);
        jMenuBar1.revalidate();
        jMenuBar1.repaint();
    }

    private void cerrarSesion() {
        int op = JOptionPane.showConfirmDialog(this, "¿Cerrar sesión?",
                "Confirmar", JOptionPane.YES_NO_OPTION);
        if (op == JOptionPane.YES_OPTION) {
            new Inicio().setVisible(true);
            this.dispose();
        }
    }


