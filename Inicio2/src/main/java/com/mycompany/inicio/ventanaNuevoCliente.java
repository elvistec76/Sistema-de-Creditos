    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
String nombre = valor(nombreTXT, PH_NOMBRE);
        String ci     = valor(ciTXT, PH_CI).toUpperCase();
        String tel    = valor(T, PH_TEL);
        String pass1  = new String(clave.getPassword());
        String pass2  = new String(clave2.getPassword());

        // --- Validaciones ---
        if (nombre.split("\\s+").length < 2) {
            aviso("Escribe tu nombre y al menos un apellido.", nombreTXT);
            return;
        }
        if (!ci.matches("[0-9]{5,10}(-[0-9A-Z]{1,2})?")) {
            aviso("CI no valido. Ejemplos: 1234567 o 1234567-1A", ciTXT);
            return;
        }
        if (!tel.matches("[0-9]{7,8}")) {
            aviso("El telefono debe tener 7 u 8 digitos, solo numeros.", T);
            return;
        }
        if (pass1.length() < 6) {
            aviso("La contraseña debe tener al menos 6 caracteres.", clave);
            return;
        }
        if (!pass1.equals(pass2)) {
            aviso("Las contraseñas no coinciden.", clave2);
            return;
        }

        // --- Armar el cliente ---
        String[] partes = separarNombre(nombre);
        Cliente c = new Cliente();
        c.setCi(ci);
        c.setNombres(partes[0]);
        c.setApellidos(partes[1]);
        c.setTelefono(tel);

        // --- Guardar cliente + cuenta ---
        try {
            new ClienteDAO().registrarConCuenta(c, pass1);
            ciGuardado = ci;
            Sesion.abrir(ci, pass1);

            JOptionPane.showMessageDialog(this,
                    "Cuenta creada correctamente."
                    + "\n\nPara ingresar al sistema usa:\n   Usuario: " + ci
                    + "\n   Contraseña: la que acabas de elegir",
                    "Registro exitoso", JOptionPane.INFORMATION_MESSAGE);

            // Bloquear el formulario y habilitar el menu
            nombreTXT.setEditable(false);
            ciTXT.setEditable(false);
            T.setEditable(false);
            clave.setText("");
            clave2.setText("");
            clave.setEditable(false);
            clave2.setEditable(false);
            btnGuardar.setEnabled(false);
            btnVentanaMenuCliente.setEnabled(true);

        } catch (SQLException | IllegalArgumentException ex) {
            if (ex instanceof SQLException sqlEx && sqlEx.getErrorCode() == 1062) {   // CI repetido
                aviso("Ya existe un cliente registrado con ese CI.", ciTXT);
            } else {
                logger.log(java.util.logging.Level.SEVERE, null, ex);
                JOptionPane.showMessageDialog(this,
                        "No se pudo guardar:\n" + ex.getMessage(),
                        "Error", JOptionPane.ERROR_MESSAGE);
            }
        }
    }//GEN-LAST:event_btnGuardarActionPerformed

