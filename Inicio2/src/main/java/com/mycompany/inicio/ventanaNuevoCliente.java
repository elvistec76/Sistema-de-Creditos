    private void placeholder(JTextField campo, String texto) {
        java.awt.Color normal = javax.swing.UIManager.getColor("TextField.foreground");
        campo.setForeground(java.awt.Color.GRAY);
        campo.setText(texto);
        campo.addFocusListener(new java.awt.event.FocusAdapter() {
            @Override
            public void focusGained(java.awt.event.FocusEvent e) {
                if (campo.getText().equals(texto)) {
                    campo.setText("");
                    campo.setForeground(normal != null ? normal : java.awt.Color.BLACK);
                }
            }
            @Override
            public void focusLost(java.awt.event.FocusEvent e) {
                if (campo.getText().trim().isEmpty()) {
                    campo.setForeground(java.awt.Color.GRAY);
                    campo.setText(texto);
                }
            }
        });
    }

    /** Devuelve lo escrito, o "" si solo esta el texto de ayuda. */
    private String valor(JTextField campo, String placeholder) {
        String t = campo.getText().trim();
        return t.equals(placeholder) ? "" : t;
    }

    /** Separa "Maria Elena Quispe Mamani" en {nombres, apellidos}. */
    private String[] separarNombre(String completo) {
        String[] p = completo.trim().split("\\s+");
        int n = p.length;
        // 2 o 3 palabras: 1 nombre. 4 o mas: los ultimos 2 son apellidos.
        int corte = (n == 2 || n == 3) ? 1 : n - 2;
        String nombres = String.join(" ", Arrays.copyOfRange(p, 0, corte));
        String apellidos = String.join(" ", Arrays.copyOfRange(p, corte, n));
        return new String[]{nombres, apellidos};
    }

