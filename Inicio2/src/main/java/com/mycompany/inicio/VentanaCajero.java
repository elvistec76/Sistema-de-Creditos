    private static final java.util.logging.Logger logger = java.util.logging.Logger.getLogger(VentanaCajero.class.getName());
  private PanelCobranza panelCobranza;   // se crea una vez y se reutiliza
 private final JPanel panelContenido = new JPanel(new BorderLayout());
    private final String login;
    public VentanaCajero() {
        this(null);
    }

    public VentanaCajero(String login) {
        Sesion.exigirRol("CAJERO");
        this.login = login;
        setTitle("Modulo de caja - " + (login == null ? "sin sesion" : login));
        setDefaultCloseOperation(DO_NOTHING_ON_CLOSE);   // el cierre pasa por salir()
        addWindowListener(new WindowAdapter() {
            @Override
            public void windowClosing(WindowEvent e) {
                salir();
            }
        });
 
        // Barra superior con el mismo estilo estandar que las otras ventanas.
        JMenuBar menu = new JMenuBar();
        JMenuItem btnInicio = new JMenuItem("Inicio");
        JMenuItem btnCobranza = new JMenuItem("Cobranza");
        JMenuItem btnPagos = new JMenuItem("Pagos registrados");
        JMenuItem btnSalir = new JMenuItem("Cerrar sesión");
 
        btnInicio.addActionListener(e -> mostrarInicio());
        btnCobranza.addActionListener(e -> mostrarCobranza());
        btnPagos.addActionListener(e -> mostrar(new PanelReporte("Pagos recibidos por " + login,
                "SELECT p.numero_comprobante AS Comprobante,p.fecha_pago AS Fecha,"
              + "cr.numero_credito AS Credito,p.monto AS Monto,p.forma_pago AS Metodo,p.estado AS Estado "
              + "FROM pago p JOIN credito cr ON cr.id_credito=p.id_credito "
              + "JOIN usuario u ON u.id_usuario=p.id_usuario WHERE u.login=? ORDER BY p.id_pago DESC", "PAGO_REGISTRAR", login)));
        btnSalir.addActionListener(e -> salir());
 
        menu.add(btnInicio);
        menu.add(btnCobranza);
        menu.add(btnPagos);
        menu.add(Box.createHorizontalGlue());
        menu.add(btnSalir);
        setJMenuBar(menu);
        setContentPane(panelContenido);
 
        setSize(1150, 700);
        setMinimumSize(new Dimension(800, 500));
        setLocationRelativeTo(null);
 
        mostrarInicio();
    }
 
    private void mostrarInicio() {
        JPanel bienvenida = new JPanel(new BorderLayout(10, 10));
        bienvenida.setBorder(BorderFactory.createEmptyBorder(50, 30, 30, 30));
 
        JLabel lbl = new JLabel(
                "<html><div style='text-align:center'>Bienvenido al modulo de caja.<br><br>"
              + "Use <b>Cobranza</b> para buscar por CI, consultar prestamos y cuotas,<br>"
              + "registrar pagos y dejar avisos internos para el cliente.</div></html>",
                SwingConstants.CENTER);
        lbl.setFont(lbl.getFont().deriveFont(Font.PLAIN, 17f));
        bienvenida.add(lbl, BorderLayout.CENTER);
 
        mostrar(bienvenida);
    }
 
    private void mostrarCobranza() {
        if (panelCobranza == null) {
            panelCobranza = new PanelCobranza(login);
        }
        mostrar(panelCobranza);
    }
 
    private void mostrar(JPanel panel) {
        panelContenido.removeAll();
        panelContenido.add(panel, BorderLayout.CENTER);
        panelContenido.revalidate();
        panelContenido.repaint();
    }
 
    private void salir() {
        int respuesta = JOptionPane.showConfirmDialog(this,
                "Deseas cerrar el modulo de caja?",
                "Confirmar salida", JOptionPane.YES_NO_OPTION);
        if (respuesta == JOptionPane.YES_OPTION) {
            dispose();
            new Inicio().setVisible(true);   // vuelve a la pantalla de inicio
        }
    }

