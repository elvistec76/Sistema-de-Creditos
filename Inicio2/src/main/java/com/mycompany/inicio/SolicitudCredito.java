    /** Pone el texto de ayuda en gris. */
    private void mostrarAyuda(JTextField campo, String texto) {
        campo.setForeground(java.awt.Color.GRAY);
        campo.setText(texto);
    }

    /** Escribe en un campo con el color normal. */
    private void escribir(JTextField campo, String texto) {
        java.awt.Color normal = javax.swing.UIManager.getColor("TextField.foreground");
        campo.setForeground(normal != null ? normal : java.awt.Color.BLACK);
        campo.setText(texto);
    }

    /** Texto gris de ayuda que desaparece al escribir y vuelve si queda vacio. */
    private void placeholder(JTextField campo, String texto) {
        java.awt.Color normal = javax.swing.UIManager.getColor("TextField.foreground");
        mostrarAyuda(campo, texto);
        campo.addFocusListener(new java.awt.event.FocusAdapter() {
            @Override
            public void focusGained(java.awt.event.FocusEvent e) {
                if (campo.getText().equals(texto)) {
                    campo.setText("");
                    campo.setForeground(normal != null ? normal : java.awt.Color.BLACK);
                }
            }
            @Override
            public void focusLost(java.awt.event.FocusEvent e) {
                if (campo.getText().trim().isEmpty()) {
                    mostrarAyuda(campo, texto);
                }
            }
        });
    }

    /** Devuelve lo escrito, o "" si solo esta el texto de ayuda. */
    private String valor(JTextField campo, String placeholder) {
        String t = campo.getText().trim();
        return t.equals(placeholder) ? "" : t;
    }

    /** Convierte el texto de un campo en numero. Devuelve null si no es valido. */
    private BigDecimal leerNumero(JTextField campo) {
        try {
            return new BigDecimal(campo.getText().trim().replace(",", "."));
        } catch (NumberFormatException e) {
            return null;
        }
    }

    /** Minusculas, sin tildes y sin espacios repetidos, para comparar nombres. */
    private String normalizar(String texto) {
        String sinTildes = java.text.Normalizer.normalize(texto, java.text.Normalizer.Form.NFD)
                .replaceAll("\\p{M}", "");
        return sinTildes.trim().replaceAll("\\s+", " ").toLowerCase();
    }

    /** Muestra un aviso y pone el cursor en el campo con problema. */
    private void aviso(String mensaje, java.awt.Component campo) {
        JOptionPane.showMessageDialog(this, mensaje, "Revisa los datos",
                JOptionPane.WARNING_MESSAGE);
        campo.requestFocus();
    }

 
