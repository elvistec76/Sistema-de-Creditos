    private void BotonGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BotonGuardarActionPerformed
 
        BotonGuardar.setSelected(false);   // es ToggleButton: lo suelta

        // 1. Leer lo que escribió la persona
        String nombre  = valor(NombreTXT, PH_NOMBRE);
        String ci      = valor(CItxt, PH_CI).toUpperCase();
        String trabajo = valor(TrabajoTXT, PH_TRABAJO);
        String destino = valor(PropositoCreditoTXT, PH_PROPOSITO);
        BigDecimal ingresos = leerNumero(IngresosTXT);
        String garantia = ListaTiposGarantiasTXT.getSelectedValue();   // null si no eligió

        // 2. Validar lo escrito, de arriba hacia abajo
        if (nombre.split("\\s+").length < 2) {
            aviso("Escribe tu nombre y al menos un apellido.", NombreTXT);
            return;
        }
        if (!ci.matches("[0-9]{5,10}(-[0-9A-Z]{1,2})?")) {
            aviso("CI no válido. Ejemplos: 1234567 o 1234567-1A", CItxt);
            return;
        }
        if (trabajo.isEmpty()) {
            aviso("Escribe el lugar donde trabajas.", TrabajoTXT);
            return;
        }
        if (ingresos == null || ingresos.signum() <= 0) {
            aviso("Escribe tus ingresos mensuales (solo números, mayor a 0).", IngresosTXT);
            return;
        }
        if (destino.isEmpty()) {
            aviso("Escribe para qué necesitas el crédito.", PropositoCreditoTXT);
            return;
        }

        // 3. Buscar al cliente por su CI y comprobar que el nombre coincide
        try {
            Cliente c = new ClienteDAO().buscarPorCi(ci);
            if (c == null) {
                aviso("No existe un cliente con ese CI.\nPrimero debes registrarte como cliente nuevo.", CItxt);
                return;
            }
            if (!normalizar(c.getNombreCompleto()).equals(normalizar(nombre))) {
                aviso("El nombre no coincide con el registrado para ese CI.", NombreTXT);
                return;
            }

            // 4. Guardar en la base (usando el CI)
            int numeroSolicitud = new SolicitudDAO().registrar(ci,
                    destino, trabajo, ingresos, garantia);

            jTextArea1.setText("SOLICITUD N° " + numeroSolicitud
                    + "\n\nCliente: " + c.getNombreCompleto()
                    + "\nPropósito: " + destino
                    + "\nGarantía: " + (garantia == null ? "ninguna" : garantia)
                    + "\nEstado: REGISTRADA"
                    + "\n\nUn analista de crédito definirá el monto, el plazo y el producto.");
            JOptionPane.showMessageDialog(this,
                    "Solicitud registrada correctamente.\nNúmero de solicitud: " + numeroSolicitud,
                    "Registro exitoso", JOptionPane.INFORMATION_MESSAGE);

            BotonGuardar.setEnabled(false);    // evita guardar dos veces lo mismo

        } catch (SQLException | IllegalArgumentException ex) {
            if (ex instanceof SQLException sqlEx && sqlEx.getErrorCode() == 1048) {   // el cliente no tiene cuenta de acceso
                JOptionPane.showMessageDialog(this,
                        "Este cliente todavía no tiene una cuenta.\n"
                        + "Debe registrarse desde «Quiero ser nuevo cliente».",
                        "Sin cuenta", JOptionPane.WARNING_MESSAGE);
            } else {
                logger.log(java.util.logging.Level.SEVERE, null, ex);
                JOptionPane.showMessageDialog(this, "No se pudo guardar:\n" + ex.getMessage(),
                        "Error", JOptionPane.ERROR_MESSAGE);
            }
        }
    }//GEN-LAST:event_BotonGuardarActionPerformed

