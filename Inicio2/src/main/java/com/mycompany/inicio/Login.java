    /** Texto gris en el campo de usuario que desaparece al escribir. */
    private void configurarTextoAyuda() {
        usuariotxt.setForeground(Color.GRAY);
        usuariotxt.setText(PH_USUARIO);
        usuariotxt.addFocusListener(new java.awt.event.FocusAdapter() {
            @Override
            public void focusGained(java.awt.event.FocusEvent e) {
                if (usuariotxt.getText().equals(PH_USUARIO)) {
                    usuariotxt.setText("");
                    usuariotxt.setForeground(Color.BLACK);
                }
            }
            @Override
            public void focusLost(java.awt.event.FocusEvent e) {
                if (usuariotxt.getText().trim().isEmpty()) {
                    usuariotxt.setForeground(Color.GRAY);
                    usuariotxt.setText(PH_USUARIO);
                }
            }
        });
    }

    private void aviso(String mensaje, java.awt.Component campo) {
        JOptionPane.showMessageDialog(this, mensaje, "Iniciar sesion",
                JOptionPane.WARNING_MESSAGE);
        campo.requestFocus();
    }

    /** Valida usuario y clave contra la base de datos y abre la ventana que corresponde. */
    private void ingresar() {
        String ci = usuariotxt.getText().trim().toUpperCase();
        if (ci.equals(PH_USUARIO.toUpperCase())) {
            ci = "";
        }
        String clave = new String(contraseñatxt.getPassword());

        if (ci.isEmpty()) {
            aviso("Escribe tu CI.", usuariotxt);
            return;
        }
        if (clave.isEmpty()) {
            aviso("Escribe tu contraseña.", contraseñatxt);
            return;
        }

        try {
            String rol = Sesion.abrir(ci, clave);

            if (rol == null) {
                aviso("CI o contraseña incorrectos.", contraseñatxt);
                contraseñatxt.setText("");
                return;
            }

            if (rol.equals("CLIENTE")) {
                new VentanaCliente(ci).setVisible(true);
                this.dispose();
            } else {
                Sesion.cerrar();
                // Los trabajadores ingresan por su acceso.
                JOptionPane.showMessageDialog(this,
                        "Ingresaste como " + rol + ".\nEsa ventana todavia no esta disponible.",
                        "Iniciar sesion", JOptionPane.INFORMATION_MESSAGE);
            }

        } catch (SQLException | IllegalArgumentException ex) {
            logger.log(java.util.logging.Level.SEVERE, null, ex);
            JOptionPane.showMessageDialog(this,
                    "No se pudo conectar con la base de datos:\n" + ex.getMessage(),
                    "Error", JOptionPane.ERROR_MESSAGE);
        }
    }

